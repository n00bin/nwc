#!/usr/bin/env node
/*
 * build-search-index.js — writes data/search-index.js, the name list behind the home-page
 * search box (gap J-6, 2026-11-02).
 *
 * Runs in .github/workflows/deploy.yml on every deploy, from the committed files only
 * (db/<type>/index.html cards + website data/*.js), so the list always matches what is
 * live and nobody has to remember to rebuild it. The output is gitignored.
 * Local test: node scripts/build-search-index.js
 *
 * Each entry is [name, type, ref, meta] and stays small for phones: the page rebuilds the link
 * (searchHref in index.html). ref = the id for mounts/companions, the file stem for db pages,
 * empty for main-page types that open by name. Results open the item on its MAIN page where one
 * exists (shared.js applyDeepLink reads ?tab= / ?q= / ?select=); everything else opens its
 * item-database page.
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const WEB = path.resolve(__dirname, "..");
const out = [];
const seen = new Set();

function add(name, type, ref, meta) {
  name = String(name || "").trim();
  if (!name) return;
  ref = ref == null ? "" : ref;
  const key = type + "|" + name.toLowerCase() + "|" + (meta || "") + "|" + ref;
  if (seen.has(key)) return;
  seen.add(key);
  const e = [name, type];
  if (ref !== "" || meta) e.push(ref);
  if (meta) e.push(meta);
  out.push(e);
}
// Same slug rule as gen-item-pages.js slugify() and searchHref() in index.html.
function slugify(s) {
  return String(s).toLowerCase().replace(/'/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "item";
}
function unescapeHtml(s) {
  return s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, "&");
}
function loadGlobal(rel, name) {
  const file = path.join(WEB, rel);
  if (!fs.existsSync(file)) return [];
  const js = fs.readFileSync(file, "utf8");
  return vm.runInNewContext(js + "\n;" + name + ";", { window: {} }) || [];
}

// db types that open on a MAIN page (link rebuilt by searchHref in index.html; keep in step).
// mounts/companions need the id (?select=); the others open by name.
const MAIN_BY_ID = new Set(["mounts", "companions"]);
const MAIN_BY_NAME = new Set(["insignias", "collars", "artifacts", "enchants", "consumables", "artisans"]);
// Types whose db rows differ only by item level etc. keep their meta so results are told apart.
const KEEP_META = new Set(["gear", "kits", "companion-gear", "overloads", "campaign-boons", "guild-boons"]);

// 1) Everything with an item-database page (read from the committed db index pages).
const dbDir = path.join(WEB, "db");
const CARD = /<a class="db-card" href="(db\/[^"]+)"[^>]*><span class="db-card-name">(?:<span[^>]*>)?([\s\S]*?)(?:<\/span>)?<\/span>(?:<span class="db-card-meta">([\s\S]*?)<\/span>)?<\/a>/g;
for (const type of fs.readdirSync(dbDir).sort()) {
  const idx = path.join(dbDir, type, "index.html");
  if (!fs.existsSync(idx)) continue;
  const html = fs.readFileSync(idx, "utf8");
  let m;
  while ((m = CARD.exec(html))) {
    const href = m[1];
    const name = unescapeHtml(m[2].replace(/<[^>]+>/g, ""));
    const meta = m[3] ? unescapeHtml(m[3].replace(/<[^>]+>/g, "")).slice(0, 40) : "";
    const id = (href.match(/\/(\d+)-[^/]*\.html$/) || [])[1];
    const stem = href.replace(/^db\/[^/]+\//, "").replace(/\.html$/, "");
    if (MAIN_BY_ID.has(type) && id) add(name, type, Number(id));
    else if (MAIN_BY_NAME.has(type)) add(name, type);
    // db file = "<id>-<slug>.html"; store just the id when the page can rebuild the slug.
    else add(name, type, id && stem === id + "-" + slugify(name) ? Number(id) : stem, KEEP_META.has(type) ? meta : "");
  }
}

// 2) Things that only live on a main page (no db page).
for (const p of loadGlobal("data/mount-combat-powers.js", "MOUNT_COMBAT_POWERS_DATA")) add(p.name, "mount-power");
for (const p of loadGlobal("data/mount-equip-powers.js", "MOUNT_EQUIP_POWERS_DATA")) add(p.name, "equip-power");
for (const p of loadGlobal("data/companion-powers.js", "COMPANION_POWERS_DATA")) add(p.name, "companion-power");
for (const e of loadGlobal("data/companion-enhancements.js", "COMPANION_ENHANCEMENTS_DATA")) add(e.name, "enhancement");
const lbFile = path.join(WEB, "data", "lockboxes.json");
if (fs.existsSync(lbFile)) {
  const lb = JSON.parse(fs.readFileSync(lbFile, "utf8"));
  for (const b of [].concat(lb.keyed_lockboxes || [], lb.related_containers || [])) add(b.name, "lockbox");
}

out.sort((a, b) => a[0].localeCompare(b[0]));
const body = "// Generated by scripts/build-search-index.js at deploy time. Do not edit or commit.\n" +
  "window.SEARCH_INDEX = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(WEB, "data", "search-index.js"), body);
const counts = {};
for (const e of out) counts[e[1]] = (counts[e[1]] || 0) + 1;
console.log("search index: " + out.length + " names, " + Math.round(body.length / 1024) + " KB");
console.log(Object.keys(counts).sort().map((k) => "  " + k + ": " + counts[k]).join("\n"));
