/* ============================================================
   MATERIALS_DATA — is a material CRAFTED or GATHERED?

   The tree can work out that a material is craftable when it already has
   that material's recipe. What it cannot work out on its own is the
   difference between:

     "this is craftable and nobody has typed the recipe yet"   <- a real gap
     "this is gathered or bought, there IS no recipe"          <- not a gap

   Without this list both look identical, so the Wanted tab ends up asking
   for recipes that will never exist. Classifying a material once fixes
   that permanently.

   {
     name:   "Hardened Mushroom",   // exactly as the game spells it
     kind:   "gathered",            // "gathered" | "crafted"
     source: "Undermountain nodes", // optional: where you get it
     notes:  ""                     // optional
   }

   kind "crafted" means the recipe exists in game but is not in the Codex
   yet — that keeps it on the Wanted list as a genuine to-do. Anything not
   listed here at all stays "unclassified" and the page asks which it is.
   ============================================================ */
